const ZONAS_EN = (zonas: { name: string; slug: string; text: string }[]) =>
  zonas.map((z) => ({ ...z, text: en.ZONAS_TEXTO_EN[z.slug] ?? z.text }));

export function textos(idioma: Idioma = "es") {
  if (idioma === "en") {
    return {
      idioma,
      ui: UI.en,
      nav: en.NAV_EN,
      cta: en.CTA_EN,
      hero: en.HERO_EN,
      nosotros: { ...es.NOSOTROS, ...en.NOSOTROS_EN },
      servicios: en.SERVICIOS_EN,
      porQue: { ...es.POR_QUE, ...en.POR_QUE_EN },
      comoFunciona: en.COMO_FUNCIONA_EN,
      galeria: en.GALERIA_EN,
      consejos: en.CONSEJOS_EN,
      confianza: en.CONFIANZA_EN,
      tiposMudanza: en.TIPOS_MUDANZA_EN,
      faq: en.FAQ_EN,
      horario: es.EMPRESA.horarioCompletoEn,
      direccion: es.EMPRESA.direccion,
      zonas: ZONAS_EN,
      whatsapp: (mensaje = "Hi, I'd like a moving quote.") => es.whatsappUrl(mensaje),
    };
  }
  return {
    idioma,
    ui: UI.es,
    nav: es.NAV.map((n) => ({ ...n, hrefLang: undefined as string | undefined })),
    cta: es.CTA,
    hero: es.HERO,
    nosotros: es.NOSOTROS,
    servicios: es.SERVICIOS,
    porQue: es.POR_QUE,
    comoFunciona: es.COMO_FUNCIONA,
    galeria: es.GALERIA,
    consejos: es.CONSEJOS,
    confianza: es.CONFIANZA,
    tiposMudanza: es.TIPOS_MUDANZA,
    faq: FAQ,
    horario: es.EMPRESA.horario,
    direccion: es.EMPRESA.direccion,
    zonas: (zonas: { name: string; slug: string; text: string }[]) => zonas,
    whatsapp: (mensaje?: string) => es.whatsappUrl(mensaje),
  };
}

export type Textos = ReturnType<typeof textos>;
